create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  pinned boolean not null default false,
  flair text not null check (flair in ('Thông báo', 'Góp ý', 'Nhận xét', 'Hỏi đáp', 'Chia sẻ')),
  title varchar(120) not null check (char_length(title) between 3 and 120),
  excerpt text not null check (char_length(excerpt) between 3 and 2000),
  username varchar(40) not null default 'khach' check (char_length(username) between 2 and 40),
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  owner_token_hash text,
  is_demo boolean not null default false,
  score integer not null default 1,
  created_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  parent_id bigint references public.comments(id) on delete cascade,
  username varchar(40) not null default 'khach' check (char_length(username) between 2 and 40),
  content text not null check (char_length(content) between 2 and 1000),
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  owner_token_hash text,
  created_at timestamptz not null default now()
);

alter table public.posts add column if not exists owner_token_hash text;
alter table public.comments add column if not exists owner_token_hash text;
alter table public.posts add column if not exists user_id uuid references auth.users(id) on delete set null default auth.uid();
alter table public.comments add column if not exists user_id uuid references auth.users(id) on delete set null default auth.uid();
alter table public.posts add column if not exists is_demo boolean not null default false;
alter table public.posts drop constraint if exists posts_flair_check;
alter table public.posts add constraint posts_flair_check check (flair in ('Thông báo', 'Góp ý', 'Nhận xét', 'Hỏi đáp', 'Chia sẻ'));

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists comments_post_id_idx on public.comments(post_id, created_at);

alter table public.posts enable row level security;
alter table public.comments enable row level security;

revoke all on table public.posts from anon, authenticated;
revoke all on table public.comments from anon, authenticated;
grant select, insert, delete on table public.posts to anon, authenticated;
grant select, insert, delete on table public.comments to anon, authenticated;
grant usage, select on sequence public.posts_id_seq, public.comments_id_seq to anon, authenticated;

drop policy if exists "Public posts are readable" on public.posts;
create policy "Public posts are readable"
on public.posts for select
to anon, authenticated
using (true);

drop policy if exists "Visitors can create posts" on public.posts;
create policy "Visitors can create posts"
on public.posts for insert
to anon, authenticated
with check (
  pinned = false
  and score between 0 and 1
  and flair in ('Góp ý', 'Nhận xét', 'Hỏi đáp', 'Chia sẻ')
  and char_length(title) between 3 and 120
  and char_length(excerpt) between 3 and 2000
  and char_length(username) between 2 and 40
  and owner_token_hash ~ '^[0-9a-f]{64}$'
);

drop policy if exists "Public comments are readable" on public.comments;
create policy "Public comments are readable"
on public.comments for select
to anon, authenticated
using (true);

drop policy if exists "Visitors can create comments" on public.comments;
create policy "Visitors can create comments"
on public.comments for insert
to anon, authenticated
with check (
  char_length(username) between 2 and 40
  and char_length(content) between 2 and 1000
  and owner_token_hash ~ '^[0-9a-f]{64}$'
);

drop policy if exists "Owners can delete posts" on public.posts;
create policy "Owners can delete posts"
on public.posts for delete
to anon, authenticated
using (
  owner_token_hash = encode(
    extensions.digest(convert_to(current_setting('app.owner_token', true), 'UTF8'), 'sha256'),
    'hex'
  )
);

drop policy if exists "Owners can delete comments" on public.comments;
create policy "Owners can delete comments"
on public.comments for delete
to anon, authenticated
using (
  owner_token_hash = encode(
    extensions.digest(convert_to(current_setting('app.owner_token', true), 'UTF8'), 'sha256'),
    'hex'
  )
);

create or replace function public.delete_own_post(target_id bigint, raw_token text)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  perform set_config('app.owner_token', raw_token, true);
  delete from public.posts where id = target_id;
  return found;
end;
$$;

create or replace function public.delete_own_comment(target_id bigint, raw_token text)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  perform set_config('app.owner_token', raw_token, true);
  delete from public.comments where id = target_id;
  return found;
end;
$$;


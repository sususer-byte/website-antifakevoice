create or replace function public.publish_next_demo_post()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  next_item public.demo_post_queue%rowtype;
  last_publish timestamptz;
  new_post_id bigint;
begin
  select max(created_at) into last_publish
  from public.posts
  where is_demo = true;

  if last_publish is not null and now() < last_publish + interval '5 hours' then
    return null;
  end if;

  select * into next_item
  from public.demo_post_queue
  where published_at is null
  order by id
  limit 1
  for update skip locked;

  if next_item.id is null then return null; end if;

  insert into public.posts (flair, title, excerpt, username, score, is_demo)
  values (next_item.flair, next_item.title, next_item.excerpt, next_item.username, next_item.score, true)
  returning id into new_post_id;

  update public.demo_post_queue set published_at = now() where id = next_item.id;
  return new_post_id;
end;
$$;

revoke all on function public.publish_next_demo_post() from public, anon, authenticated;

